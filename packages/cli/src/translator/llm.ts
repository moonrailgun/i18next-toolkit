import { config } from '../config';

function generateTermsInstruction(): string {
  const terms = config.translator?.terms ?? [];
  return terms.length > 0
    ? '\n\nThe following proper nouns MUST be kept in their original form and never translated:\n' +
        terms.map((term) => `- ${term}`).join('\n')
    : '';
}

export function generateOpenAITranslateSystemPrompt(locale: string): string {
  return `
You are a professional translation tool specialized in handling JSON data within a software development context.
The input is a flat JSON object where each key is a hash value generated by a computer program (e.g., MD5, SHA-256). These keys should remain unchanged.
Your task is to translate the textual content of each value into '${locale}'.

Requirements:
1. Do not translate or modify the keys.
2. Translate every value completely into '${locale}'. By default, all words and phrases must be translated, including ordinary nouns, verbs, and user-facing labels. Do not leave any part of a value in the source language unless it falls under an explicit exception in requirement 3.
3. Keep a token in its original form only if it is an established acronym or initialism (e.g. API, JSON, URL), a code-level identifier such as a variable, function, or file name, or a term listed in the glossary below. When unsure whether a word qualifies, translate it.
4. Maintain the flat JSON structure; the output must be valid JSON.${generateTermsInstruction()}
`.trim();
}

export function generateLLMTranslatePrompt(
  untranslated: Record<string, Record<string, string>>
): string {
  return (
    'Please make sure all result should return with code block.' +
    generateTermsInstruction() +
    '\n\n' +
    Object.entries(untranslated)
      .map(([locale, trans]) => {
        return `Please help me translate those file to \`${locale}\`:\n\n${JSON.stringify(
          trans,
          null,
          2
        )}`;
      })
      .join('\n\n')
  );
}
